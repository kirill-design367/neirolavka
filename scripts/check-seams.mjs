/**
 * Стык между секциями: резкий перепад фона по вертикали.
 * Идём сверху вниз по узкой полосе слева от содержимого и смотрим,
 * насколько сильно меняется цвет фона от строки к строке.
 * Плавный переход даёт мелкие шаги, стык — один большой скачок.
 *
 * Проходов ДВА, и спрашивают они разное.
 *
 * Первый — про стыки самой ВЁРСТКИ. Он открывает страницу с
 * выключенным движением, и холста пузырей в DOM нет вовсе: компонент
 * его удаляет. В кадре остаются только фоны секций — ровно то, ради
 * чего скрипт написан.
 *
 * Второй — про КРОМКУ ХОЛСТА пузырей. Холст переехал из первого
 * экрана в первые дети body и закреплён по окну (position: fixed;
 * inset: 0), то есть висит на любой высоте прокрутки. Значит у него
 * появилась своя горизонтальная кромка, и она тоже может оказаться
 * той самой линией. Первый проход увидеть её не может — там холста
 * нет.
 */
import { chromium } from 'playwright';
import fs from 'node:fs';
import { PNG } from 'pngjs';
const URL = process.argv[2];
const b = await chromium.launch({ executablePath: (process.env.CHROME_PATH || '/opt/pw-browsers/chromium-1194/chrome-linux/chrome') });
let bad = 0;
console.log('Стыки вёрстки (движение выключено, холста пузырей в DOM нет)');
for (const theme of ['light', 'dark']) {
  const c = await b.newContext({ viewport: { width: 1512, height: 900 }, locale: 'ru-RU', reducedMotion: 'reduce' });
  await c.addInitScript((t) => localStorage.setItem('neirolavka-theme', t), theme);
  const p = await c.newPage();
  await p.goto(URL, { waitUntil: 'networkidle' });
  await p.waitForTimeout(600);
  const buf = await p.screenshot({ fullPage: true, clip: undefined });
  const png = PNG.sync.read(buf);
  // узкая полоса у левого края — там нет карточек, только фон секций
  const X = 20;
  const col = [];
  for (let y = 0; y < png.height; y++) {
    const i = (png.width * y + X) << 2;
    col.push([png.data[i], png.data[i + 1], png.data[i + 2]]);
  }
  let worst = 0, worstY = 0;
  for (let y = 1; y < col.length; y++) {
    const d = Math.hypot(col[y][0]-col[y-1][0], col[y][1]-col[y-1][1], col[y][2]-col[y-1][2]);
    if (d > worst) { worst = d; worstY = y; }
  }
  const ok = worst < 6;
  if (!ok) bad++;
  console.log(`  ${ok ? 'ok ' : 'СТЫК'} ${theme === 'dark' ? 'тёмная' : 'светлая'}: самый резкий перепад фона ${worst.toFixed(1)} из 255 на высоте ${worstY} px`);
  await c.close();
}

/* ─── Проход 2: кромка холста пузырей ───────────────────────────
 *
 * На снимке всей страницы закреплённый по окну холст остаётся ростом
 * в окно и прижат к верху кадра — значит его нижняя кромка обнажена
 * ровно на высоте окна, там, где на живой странице её загораживает
 * край экрана. Это и есть предмет замера: начни холст красить не
 * только точки — своим фоном, непрозрачной очисткой, каймой у края, —
 * и по всей ширине страницы ляжет линия.
 *
 * Порог тут не может быть тем же, и вот почему. Пузырь — это краска
 * на фоне: его точки мельче, чем растяжение холста до размера окна,
 * и построчный перепад на них доходит до 149 из 255 в светлой теме
 * и до 114 в тёмной. Для первого прохода это стык, для второго —
 * норма. Величиной перепада их не различить вовсе.
 *
 * Различает ШИРИНА. Стык — линия во всю страницу: он меняет ВСЕ
 * столбцы разом в одной строке. Пузырь местный и шире своего
 * поперечника быть не может. Поэтому «резким» перепад считается
 * по тому же порогу 6 из 255, что и в первом проходе, а вердикт
 * ставится по ДОЛЕ полосы, на которой он случился в одной строке.
 *
 * Числа порога. На исправной сборке наибольшая доля за прогон —
 * 12.8…32.1 % (шестнадцать прогонов, обе темы; ещё в трёх кадрах
 * в полосу не залетело ни одного пузыря — про это ниже отдельно).
 * Геометрический потолок выше замеренного: самый крупный пузырь
 * 54 px радиусом, то есть 108 px поперёк при полосе в 290 столбцов —
 * 37 % на один пузырь и до 74 %, если по крупному пузырю встанет
 * в каждое поле на одной высоте. Стык же по построению даёт 100 %:
 * замер на холсте, которому добавлена заливка, показал ровно 100 %
 * и ровно на высоте окна. Порог 80 % лежит выше двухпузырного
 * потолка и заведомо ниже стыка.
 *
 * Отвергнутые меры, обе молчали на настоящем стыке или кричали на
 * исправной сборке: наибольший перепад по полосе (исправная 106–149,
 * стык 200–270 — разделяет только в одну сторону) и медиана перепада
 * поперёк полосы (1.7 всегда: пузыри не занимают половины полосы,
 * и мера не видит вообще ничего). */
const POROG_REZKOSTI = 6;     // тот же «резкий перепад», что в первом проходе
const POROG_DOLI = 0.8;       // какую долю полосы он должен занять, чтобы считаться линией
// Чистые поля страницы при ширине окна 1512: замер по вёрстке
// показал, что содержимое не заходит левее столбца 159 и правее
// столбца 1347 ни на одной высоте. Пузыри в эти поля залетают,
// карточки и текст — никогда.
const CHISTOE = [];
for (let x = 8; x <= 152; x++) CHISTOE.push(x);
for (let x = 1356; x <= 1500; x++) CHISTOE.push(x);

console.log('\nКромка холста пузырей (движение включено, пузыри живые)');
for (const theme of ['light', 'dark']) {
  const c = await b.newContext({ viewport: { width: 1512, height: 900 }, locale: 'ru-RU' });
  await c.addInitScript((t) => localStorage.setItem('neirolavka-theme', t), theme);
  const p = await c.newPage();
  await p.goto(URL, { waitUntil: 'networkidle' });
  // Ждём СОБЫТИЕ, а не паузу: холст скрыт до первого resize() и
  // показывается сам, когда геометрия задана. Фиксированная пауза
  // здесь была бы гонкой — кусок с отрисовкой едет по сети.
  let est = true;
  try {
    await p.waitForFunction(() => {
      const cv = document.querySelector('canvas.bubbles');
      return !!cv && getComputedStyle(cv).visibility === 'visible';
    }, null, { timeout: 8000 });
  } catch { est = false; }
  if (!est) {
    // Ненайденный предмет пробы — отказ, а не заметка: без холста
    // этот проход не меряет ничего и обязан сказать об этом вслух.
    bad++;
    console.log(`  НЕТ  ${theme === 'dark' ? 'тёмная' : 'светлая'}: холста canvas.bubbles на странице нет — мерить нечего`);
    await c.close();
    continue;
  }
  /* Кадр, в котором в полосе полей нет НИ ОДНОГО резкого перепада,
     не говорит ничего: значит в поля не залетело ни одного пузыря,
     и проход не померил ничего. Такое выпадает примерно раз из
     шести — пузырей девятнадцать на всё окно, а поля занимают
     290 столбцов из 1512. Поэтому кадр берётся не первый попавшийся:
     снимаем, пока краска в полосе не появится, — пузыри плывут сами,
     и ждать тут можно только их. Не дождались за шесть кадров — это
     отказ, а не «ok»: молчащая проверка опаснее упавшей. */
  let worst = 0, worstY = 0, kadr = 0;
  for (kadr = 1; kadr <= 6; kadr++) {
    const png = PNG.sync.read(await p.screenshot({ fullPage: true }));
    worst = 0; worstY = 0;
    for (let y = 1; y < png.height; y++) {
      let n = 0;
      for (const x of CHISTOE) {
        const i0 = (png.width * (y - 1) + x) << 2;
        const i1 = (png.width * y + x) << 2;
        const d = Math.hypot(png.data[i1]-png.data[i0], png.data[i1+1]-png.data[i0+1], png.data[i1+2]-png.data[i0+2]);
        if (d >= POROG_REZKOSTI) n++;
      }
      const dolya = n / CHISTOE.length;
      if (dolya > worst) { worst = dolya; worstY = y; }
    }
    if (worst > 0) break;
    await p.waitForTimeout(500);
  }
  if (worst === 0) {
    bad++;
    console.log(`  ПУСТО ${theme === 'dark' ? 'тёмная' : 'светлая'}: за шесть кадров в полосу полей не залетело ни одного пузыря — проход не померил ничего`);
    await c.close();
    continue;
  }
  const ok = worst < POROG_DOLI;
  if (!ok) bad++;
  console.log(`  ${ok ? 'ok ' : 'СТЫК'} ${theme === 'dark' ? 'тёмная' : 'светлая'}: резкий перепад занял ${(worst * 100).toFixed(1)} % полосы полей на высоте ${worstY} px (у линии во всю ширину было бы 100 %), кадр ${kadr}`);
  await c.close();
}
await b.close();
console.log(bad ? '\nЕсть резкие стыки' : '\nРезких стыков нет, фон течёт непрерывно');
process.exit(bad ? 1 : 0);
