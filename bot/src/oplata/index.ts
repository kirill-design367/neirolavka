/**
 * Место под оплату.
 *
 * Оплата подключается следующим заходом, но проём под неё вырублен
 * сейчас — иначе потом пришлось бы переписывать путь заказа, а он
 * к тому времени будет боевым.
 *
 * Устройство: заказ создаётся ВСЕГДА, платёж — отдельная сущность
 * рядом с ним. Поставщик оплаты отвечает на два вопроса: «как человеку
 * заплатить» и «этот платёж настоящий». Всё остальное — общее.
 *
 * Единственная дверь, через которую заказ становится оплаченным, —
 * zakazy.otmetitOplachennym. Сейчас в неё стучится администратор
 * кнопкой, потом будет стучаться уведомление ЮKassa. Тело двери
 * не меняется.
 */

import type { Zakaz } from '../db/zakazy.js';

export type Schet = {
  /** Идентификатор платежа у поставщика. Пусто, пока платежа нет. */
  vneshnyId: string | null;
  /** Куда отправить человека платить. Пусто — платить пока негде. */
  adres: string | null;
  /** Текст, который бот покажет вместо кнопки оплаты. */
  soobshchenie: string;
  /** Можно ли считать заказ оплаченным сразу (никогда — у настоящих). */
  gotovoSrazu: boolean;
};

/** Разобранное уведомление поставщика. */
export type Uvedomlenie = {
  vneshnyId: string;
  zakazId: number;
  summaKop: number;
  oplachen: boolean;
};

export type PostavshchikOplaty = {
  /** Имя, под которым платежи ложатся в базу. */
  imya: string;
  /** true, если оплату уже можно принимать. */
  rabotaet: boolean;
  /** Выставить счёт по заказу. */
  vystavit(zakaz: Zakaz): Promise<Schet>;
  /**
   * Разобрать и ПРОВЕРИТЬ уведомление.
   *
   * Проверка подписи живёт здесь же, а не в обработчике вебхука:
   * иначе однажды появится второй обработчик без проверки.
   */
  razobratUvedomlenie(telo: string, zagolovki: Record<string, string | string[] | undefined>): Uvedomlenie | null;
};
