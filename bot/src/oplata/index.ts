/**
 * Приём оплаты: общий тип поставщика.
 *
 * Устройство: заказ создаётся ВСЕГДА, платёж — отдельная сущность
 * рядом с ним. Поставщик отвечает на два вопроса: «как человеку
 * заплатить» и «это уведомление настоящее». Всё остальное — общее
 * и от поставщика не зависит.
 *
 * Единственная дверь, через которую заказ становится оплаченным, —
 * `zakazy.otmetitOplachennym`. В неё стучится и администратор
 * кнопкой, и уведомление Робокассы. Тело двери при появлении оплаты
 * не изменилось ни строкой — ради этого тип и был вырублен заранее.
 */

import type { Zakaz } from '../db/zakazy.js';

/**
 * Запрос на выставление счёта.
 *
 * НОМЕР СЧЁТА ПРИХОДИТ СНАРУЖИ, а не придумывается поставщиком,
 * и это главное в этом типе. Номер обязан быть уникальным на КАЖДУЮ
 * оплату: повторный номер Робокасса встречает ошибкой 40 («повторная
 * оплата счёта с тем же номером невозможна»). Уникальность даёт
 * база — строка в `platezhi` с её AUTOINCREMENT, — а не счётчик
 * в памяти процесса, который обнуляется при каждой выкладке.
 *
 * СУММА — ТОЖЕ СНАРУЖИ, и это не то же самое, что цена заказа:
 * человек мог закрыть часть баланса и часть промокодом. Платить
 * он должен ровно остаток.
 */
export type ZaprosScheta = {
  zakaz: Zakaz;
  /** Номер счёта: уникален на каждую оплату, не равен номеру заказа. */
  nomer: number;
  /** Сколько осталось заплатить деньгами, копейками. */
  summaKop: number;
};

export type Schet = {
  /** Идентификатор платежа у поставщика. Пусто, пока платежа нет. */
  vneshnyId: string | null;
  /** Куда отправить человека платить. Пусто — платить пока негде. */
  adres: string | null;
  /** Текст, который бот покажет рядом с кнопкой оплаты. */
  soobshchenie: string;
  /** Можно ли считать заказ оплаченным сразу (никогда — у настоящих). */
  gotovoSrazu: boolean;
};

/**
 * Разобранное и ПРОВЕРЕННОЕ уведомление поставщика.
 *
 * `nomer` — номер счёта, а не заказа: заказ находится по нему
 * в таблице платежей. Класть номер заказа прямо в уведомление
 * значило бы доверять тому, что прислали снаружи.
 */
export type Uvedomlenie = {
  nomer: number;
  summaKop: number;
  oplachen: boolean;
};

export type PostavshchikOplaty = {
  /** Имя, под которым платежи ложатся в базу. */
  imya: string;
  /** true, если оплату уже можно принимать. */
  rabotaet: boolean;
  /** Выставить счёт. */
  vystavit(z: ZaprosScheta): Promise<Schet>;
  /**
   * Разобрать и ПРОВЕРИТЬ уведомление.
   *
   * Проверка подписи живёт здесь же, а не в обработчике вебхука:
   * иначе однажды появится второй обработчик без проверки. Всё,
   * что не сошлось, — это `null`, и вызывающий обязан ответить
   * отказом, ничего не меняя.
   */
  razobratUvedomlenie(pary: Record<string, string>): Uvedomlenie | null;
};
