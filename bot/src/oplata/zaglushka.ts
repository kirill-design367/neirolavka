/**
 * Заглушка оплаты.
 *
 * Ничего не принимает и делает это честно: счёт не выставляется,
 * человеку говорится, что оплата не подключена, заказ при этом
 * создаётся и уходит администратору — деньги ходят мимо бота,
 * а подтверждает их человек.
 *
 * Осталась в проекте после подключения Робокассы НАРОЧНО, и вот
 * зачем: настройки Робокассы могут быть не заполнены (новый сервер,
 * стенд проверок, забытая переменная). Выбор тогда не между
 * «работает» и «падает», а между «работает» и «честно говорит,
 * что оплаты нет»: заказ обязан приниматься в обоих случаях.
 */

import type { PostavshchikOplaty, RazborUvedomleniya, Schet } from './index.js';

export const zaglushka: PostavshchikOplaty = {
  imya: 'zaglushka',
  rabotaet: false,
  async vystavit(): Promise<Schet> {
    return {
      vneshnyId: null,
      adres: null,
      soobshchenie:
        'Оплата в боте пока не подключена. Заказ я записал и передал администратору — ' +
        'он напишет вам, как заплатить.',
      gotovoSrazu: false,
    };
  },
  razobratUvedomlenie(pary: Record<string, string>): RazborUvedomleniya {
    // Настоящих уведомлений пока не бывает. Отвечать «принято»
    // на то, чего мы не проверяли, нельзя — но и молчать о причине
    // тоже: «оплата не настроена» и «подпись не сошлась» лечатся
    // совершенно по-разному.
    return {
      vzyali: false,
      pochemu: 'podpis_ne_soshlas',
      slovami: 'оплата не подключена: проверять подпись нечем',
      podpisnye: {},
      imena: Object.keys(pary).sort(),
      podpisPrishla: '',
    };
  },
};
