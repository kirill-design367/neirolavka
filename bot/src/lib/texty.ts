/**
 * Отмена. Текст владельца дан для одной причины — «недостаточно
 * средств»; остальные набраны по тому же образцу, потому что три
 * разных формы одного сообщения разъехались бы на первой правке.
 *
 * Три вещи обязательны в любом случае: что отменено, почему и куда
 * делись деньги. Молчание про деньги — ровно то, из-за чего пишут
 * в поддержку.
 */
export function zakazOtmenen(
  z: Zakaz,
  prichina: PrichinaOtmeny,
  vernuli: number,
  balansKop: number,
): string {
  void z;
  const strok = [`Ваш заказ был отменён: ${prichinaSlovami(prichina)}.`];
  if (prichina === 'net_koda') {
    strok.push(
      '',
      'Код с почты так и не пришёл, а держать заказ дольше обещанного ' +
        'срока я не могу. Пожалуйста, оформите заказ заново.',
    );
  }
  if (prichina === 'nevernyy_parol') {
    strok.push(
      '',
      'На Вашу почту отправлено письмо для восстановления пароля — ' +
        'восстановите доступ и оформите заказ заново.',
    );
  }
  if (prichina === 'net_deneg') {
    strok.push('', 'Пожалуйста, пополните баланс и оформите заказ заново.');
  }
  if (vernuli > 0) {
    strok.push('', `Деньги вернулись на баланс: ${rubli(vernuli)}.`);
  }
  strok.push('', `Ваш баланс: ${rubli(balansKop)}`);
  strok.push(
    '',
    'Если это неожиданность, пожалуйста напишите в поддержку и мы во всём разберёмся.',
  );
  return strok.join('\n');
}

/* ── баланс ──────────────────────────────────────────────────────── */

export function vidDvizheniyaSlovami(vid: string): string {
  switch (vid) {
    case 'popolnenie':
      return 'пополнение';
    case 'vozvrat':
      return 'возврат';
    default:
      return 'оплата заказа';
  }
}

/**
 * Баланс покупателя.
 *
 * Показывается сумма и последние движения. Вывода средств тут нет
 * и не будет: баланс — способ заплатить в лавке, а не счёт, с которого
 * забирают деньги. Поэтому и кнопки такой нет — не «спрятана», а
 * не существует.
 */
export function balansEkran(
  balansKop: number,
  dvizheniya: { kop: number; vid: string; za_chto: string; kogda: string }[],
  poyas: string,
): string {
  const hvost = [
    '',
    'Заказ оплачивается с Вашего баланса — целиком или частично. ' +
      'При оформлении заказа деньги спишутся автоматически.',
  ];
  const strok = [`Ваш баланс: ${rubli(balansKop)}`];
  if (!dvizheniya.length) {
    strok.push(
      '',
      'Операций пока не было. Баланс пополняется при возврате по отменённому ' +
        'заказу — и администратором, если Вы договорились об этом отдельно.',
      ...hvost,
    );
    return strok.join('\n');
  }
  strok.push('', 'Последние операции:', '');
  /* Вид движения и дата остаются, хотя в строке владельца стоит одна
     сумма со знаком: «−900 ₽» без «за что» и «когда» — это список,
     по которому нельзя понять ничего, а ради понимания он и показан. */
  for (const d of dvizheniya) {
    const znak = d.kop > 0 ? '+' : '−';
    strok.push(
      `${znak}${rubli(Math.abs(d.kop))} · ${vidDvizheniyaSlovami(d.vid)} · ` +
        `${momentSlovami(new Date(d.kogda), poyas)}`,
    );
  }
  strok.push(...hvost);
  return strok.join('\n');
}

