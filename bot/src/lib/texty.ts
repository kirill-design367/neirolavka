/**
 * Проверка состава заказа — перед нажатием «Оформить».
 *
 * ТЕКСТ ВЛАДЕЛЬЦА, дословно. Две вещи, которых в его строках нет
 * и которые здесь всё же стоят, названы прямо:
 *
 * 1. `chto` — строка «что получаешь» из каталога. Нужна продукту БЕЗ
 *    уровней подписки: у него эта карточка стоит вместо карточки
 *    товара, и без неё человек видел бы одно голое название.
 * 2. Промокод и итог. Человек видел сумму со скидкой на сайте; если
 *    в боте стоит другая, он решит, что скидку не засчитали, и
 *    не дойдёт до конца.
 *
 * «Стоимость (1 мес)» — слова владельца. До сентября 2026 срок
 * подписки не был объявлен вовсе, и выводить его было не из чего;
 * теперь он объявлен этой строкой. Число в скобках — часть текста
 * владельца, а не расчёт: в каталоге срока по-прежнему нет,
 * и вычислять дату окончания доступа не из чего.
 */
export function podtverzhdenie(
  nazvanie: string,
  cenaKop: number,
  srok: Srok,
  r: Raspisanie,
  chto?: string,
  promo?: { kod: string; skidkaProc: number; skidkaKop: number } | null,
): string {
  const dengi = promo
    ? [
        `Стоимость (1 мес): ${rubliIli(cenaKop)}`,
        `Промокод ${promo.kod}: −${promo.skidkaProc} % (−${rubli(promo.skidkaKop)})`,
        `К оплате: ${rubli(Math.max(0, cenaKop - promo.skidkaKop))}`,
      ]
    : [`Стоимость (1 мес): ${rubliIli(cenaKop)}`];
  return [
    'Пожалуйста, проверьте состав заказа:',
    '',
    `Товар: ${nazvanie}`,
    ...(chto ? [chto] : []),
    ...dengi,
    `Когда будет выполнен: ${kogdaPridet(srok, r)}`,
    '',
    'Логин и пароль от нового аккаунта придут в этот чат. ' +
      'Также их можно посмотреть в разделе «Мои заказы».',
  ].join('\n');
}

/** Обещание по конкретному заказу. Верхняя граница, а не идеал. */
export function kogdaPridet(srok: Srok, r: Raspisanie): string {
  if (!srok.utrom) {
    return `сегодня, не позже ${chasyMinuty(srok.do, r.poyas)}`;
  }
  return `утром, после ${chasSlovami(r.rabotaS)} по МСК — сейчас лавка закрыта`;
}

/**
 * Тот же срок, но одним МОМЕНТОМ: «13 сентября, 14:30».
 *
 * Нужен там, где владелец написал «не позднее — {N}»: подставить
 * туда `kogdaPridet` значило бы получить «не позднее — сегодня,
 * не позже 14:30», то есть сказать одно и то же дважды. Дата здесь
 * не лишняя: ночной заказ уезжает на следующий день, и «не позднее
 * 10:30» без числа читалось бы как «сегодня».
 */
export function srokSlovami(srok: Srok, r: Raspisanie): string {
  return momentSlovami(srok.do, r.poyas);
}

/**
 * Заказ принят.
 *
 * ДВА ТЕКСТА ВЛАДЕЛЬЦА В ОДНОЙ ФУНКЦИИ: «заказ создан и оплачен»
 * (баланса хватило целиком) и «заказ создан» (осталось заплатить).
 * Развилка одна — статус заказа, — поэтому и функция одна: два
 * похожих текста в разных местах разъехались бы на первой правке.
 *
 * Чего в словах владельца нет и что здесь всё же стоит:
 *   • строки промокода — человек видел сумму со скидкой на сайте;
 *   • честная оговорка на случай, когда оплата НЕ настроена. Она
 *     не выдумка на будущее: настройки Робокассы могут быть пусты
 *     на новом сервере, и заказ обязан приниматься и тогда.
 *
 * НОМЕРА ЗАКАЗА ЗДЕСЬ НЕТ, и это решение владельца: покупателю
 * везде «Ваш заказ». Номер остался у помощника — им он привязывает
 * код двухфакторной аутентификации к заказу.
 */
export function zakazPrinyat(o: {
  zakaz: Zakaz;
  srok: Srok;
  r: Raspisanie;
  oplataRabotaet: boolean;
  /** Сколько ушло с баланса при оформлении. */
  spisano: number;
  /** Что осталось на балансе после списания. */
  balansKop: number;
  /** Промокод, который человек принёс, но применить не вышло. */
  promoNePodoshel?: { kod: string; pochemu: string } | null;
}): string {
  const { zakaz, srok, r, spisano } = o;
  const oplachen = zakaz.status !== 'zhdet_oplaty';
  const strok = oplachen
    ? [
        'Ваш заказ создан и оплачен. Как только его примут в работу, ' +
          'Вы получите уведомление. Доступ придёт в этот чат, не позднее — ' +
          `${srokSlovami(srok, r)}.`,
      ]
    : ['Ваш заказ создан.'];

  strok.push('', `${zakaz.nazvanie} — ${rubliIli(zakaz.cena_kop)}`);

  /* Скидка называется ОТДЕЛЬНОЙ СТРОКОЙ, а не подменяет цену.
     Человек должен видеть, что промокод сработал и на сколько:
     одна итоговая сумма не отличается от «цена такая и была». */
  if (zakaz.skidka_kop > 0 && zakaz.promo_kod) {
    strok.push(
      `Промокод ${zakaz.promo_kod}: −${rubli(zakaz.skidka_kop)}`,
      `К оплате: ${rubli(Math.max(0, zakaz.cena_kop - zakaz.skidka_kop))}`,
    );
  }

  /* Код не подошёл — говорим сразу и словами. Промолчать значило бы
     оставить человека считать, что скидка внутри суммы. */
  if (o.promoNePodoshel) {
    strok.push('', `Промокод ${o.promoNePodoshel.kod} не применился: ${o.promoNePodoshel.pochemu}`);
  }

  if (spisano > 0) {
    strok.push('', `С баланса списано ${rubli(spisano)}. Ваш баланс: ${rubli(o.balansKop)}.`);
  }

  if (!oplachen) {
    strok.push(
      '',
      o.oplataRabotaet
        ? 'Оплатите заказ по кнопке ниже, чтобы он был принят в работу.'
        : 'Оплата в боте пока не подключена, и придумывать её я не буду. ' +
          'Заказ уже у администратора: он напишет вам сюда и скажет, как заплатить.',
    );
  }

  strok.push('', 'Также информацию о заказе можно посмотреть в разделе «Мои заказы».');
  return strok.join('\n');
}

