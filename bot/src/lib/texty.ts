export const NAZVANIE = 'Нейролавка';

export function privetstvie(imya: string, r: Raspisanie): string {
  const kak = imya ? `${imya}, здравствуйте.` : 'Здравствуйте.';
  return [
    `${kak} Это ${NAZVANIE} — здесь продают доступ к нейросетям по подписке.`,
    '',
    'Как это устроено. Вы выбираете нейросеть и подписку, оплачиваете, ' +
      'а доступ — логин и пароль — присылаю сюда же, в этот чат. ' +
      'Доступы выдаёт человек, поэтому не мгновенно, но и не «когда-нибудь»: ' +
      `${obeshchanieVoobshche(r)}.`,
    '',
    /* ЭТА СТРОКА БЫЛА ВРАНЬЁМ, и вот каким. Стояло «Ничего, кроме
       вашего Telegram, я не спрашиваю: ни почты, ни телефона, ни
       данных карты». Телефона и карты бот правда не спрашивает —
       а вот логин почты и пароль от аккаунта спрашивает у каждого,
       кто продлевает СВОЙ аккаунт, и с сентября 2026 ещё и показывает
       их на экране сверки. То есть обещание опровергалось следующим
       же сообщением того же бота.

       Обещать меньше, чем берёшь, — худший вид неправды на витрине,
       где и так платят вперёд незнакомцу: человек ловит подмену
       сам, и дальше не верит уже ничему. Поэтому оговорка названа
       прямо, а взамен сказано то, что действительно снимает страх:
       эти данные шифруются и стираются из переписки. И то и другое
       правда — AES-256-GCM с ключом в /etc, сообщение удаляется
       сразу после прочтения. */
    'Телефон и данные карты я не спрашиваю. Логин и пароль нужны ' +
      'только если продлеваете свой аккаунт: они шифруются, ' +
      'а сообщение с ними я удаляю из переписки сразу.',
  ].join('\n');
}

/** Общее обещание для приветствия — без привязки к конкретному заказу. */
export function obeshchanieVoobshche(r: Raspisanie): string {
  const skolko = r.obeshchanieMinut >= 60
    ? sklonenie(Math.round(r.obeshchanieMinut / 60), 'часа', 'часов', 'часов')
    : sklonenie(r.obeshchanieMinut, 'минуты', 'минут', 'минут');
  return (
    `в рабочие часы, с ${chasSlovami(r.rabotaS)} до ${chasSlovami(r.rabotaDo)} по Москве, ` +
    `в течение ${skolko}; ночной заказ уходит в работу утром`
  );
}

