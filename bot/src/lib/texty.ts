/**
 * Карточка заказа до оформления: что именно человек берёт.
 *
 * `chto` — строка «что получаешь» из каталога. Нужна продукту БЕЗ
 * уровней подписки: у него эта карточка стоит вместо карточки товара,
 * и без неё человек видел бы одно голое название.
 *
 * Строки «Срок: N месяцев, доступ до …» здесь нет и не будет. Тарифом
 * теперь называется УРОВЕНЬ подписки, а не срок; срок владелец
 * не объявлял, и выводить дату не из чего.
 */
export function podtverzhdenie(
  nazvanie: string,
  cenaKop: number,
  srok: Srok,
  r: Raspisanie,
  chto?: string,
  /* Промокод, который человек принёс, — если он подходит к этому
     выбору. Показать его НАДО ЗДЕСЬ, до нажатия «Оформить»: человек
     видел сумму со скидкой на сайте, и если в боте стоит другая,
     он решит, что скидку не засчитали, и не дойдёт до конца. */
  promo?: { kod: string; skidkaProc: number; skidkaKop: number } | null,
): string {
  const dengi = promo
    ? [
        `Сколько: ${rubliIli(cenaKop)}`,
        `Промокод ${promo.kod}: −${promo.skidkaProc} % (−${rubli(promo.skidkaKop)})`,
        `К оплате: ${rubli(Math.max(0, cenaKop - promo.skidkaKop))}`,
      ]
    : [`Сколько: ${rubliIli(cenaKop)}`];
  return [
    'Проверьте заказ.',
    '',
    `Что: ${nazvanie}`,
    ...(chto ? [chto] : []),
    ...dengi,
    `Когда придёт: ${kogdaPridet(srok, r)}`,
    '',
    'Доступ приходит в этот чат: логин и пароль от готового аккаунта. ' +
      'Их можно будет посмотреть ещё раз в разделе «Мои заказы».',
  ].join('\n');
}

/** Обещание по конкретному заказу. Верхняя граница, а не идеал. */
export function kogdaPridet(srok: Srok, r: Raspisanie): string {
  if (!srok.utrom) {
    return `сегодня, не позже ${chasyMinuty(srok.do, r.poyas)}`;
  }
  return `утром, после ${chasSlovami(r.rabotaS)} по Москве — сейчас лавка закрыта`;
}

/**
 * Заказ принят.
 *
 * Три вещи, которые человек обязан увидеть сразу: что записано,
 * что стало с деньгами (баланс списывается при оформлении) и что
 * будет дальше. Про баланс молчать нельзя: списание без объяснения —
 * это первое, из-за чего пишут в поддержку.
 */
export function zakazPrinyat(o: {
  zakaz: Zakaz;
  srok: Srok;
  r: Raspisanie;
  oplataRabotaet: boolean;
  /** Сколько ушло с баланса при оформлении. */
  spisano: number;
  /** Что осталось на балансе после списания. */
  balansKop: number;
  /** Промокод, который человек принёс, но применить не вышло. */
  promoNePodoshel?: { kod: string; pochemu: string } | null;
}): string {
  const { zakaz, srok, r, spisano } = o;
  const strok = [`Заказ № ${zakaz.id} записан.`, '', `${zakaz.nazvanie} — ${rubliIli(zakaz.cena_kop)}`];

  /* Скидка называется ОТДЕЛЬНОЙ СТРОКОЙ, а не подменяет цену.
     Человек должен видеть, что промокод сработал и на сколько:
     одна итоговая сумма не отличается от «цена такая и была». */
  if (zakaz.skidka_kop > 0 && zakaz.promo_kod) {
    strok.push(
      `Промокод ${zakaz.promo_kod}: −${rubli(zakaz.skidka_kop)}`,
      `К оплате: ${rubli(Math.max(0, zakaz.cena_kop - zakaz.skidka_kop))}`,
    );
  }

  /* Код не подошёл — говорим сразу и словами. Промолчать значило бы
     оставить человека считать, что скидка внутри суммы. */
  if (o.promoNePodoshel) {
    strok.push('', `Промокод ${o.promoNePodoshel.kod} не применился: ${o.promoNePodoshel.pochemu}`);
  }

  if (spisano > 0) {
    strok.push('', `С баланса списано ${rubli(spisano)}. Осталось на балансе ${rubli(o.balansKop)}.`);
  }

  if (zakaz.status !== 'zhdet_oplaty') {
    strok.push('', 'Заказ оплачен полностью. Помощник возьмёт его в работу — ' + `доступ придёт ${kogdaPridet(srok, r)}.`);
  } else if (o.oplataRabotaet) {
    strok.push('', 'Осталось оплатить — кнопка ниже.');
  } else {
    strok.push(
      '',
      'Оплата в боте пока не подключена, и придумывать её я не буду. ' +
        'Заказ уже у администратора: он напишет вам сюда и скажет, как заплатить.',
      '',
      `После оплаты доступ придёт ${kogdaPridet(srok, r)}.`,
    );
  }

  if (zakaz.vid_akkaunta === 'svoy') {
    strok.push(
      '',
      'Аккаунт ваш: когда помощник начнёт вход, на вашу почту придёт код ' +
        'подтверждения — я попрошу прислать его сюда.',
    );
  }

  strok.push('', 'Заказ никуда не денется: он записан и виден в разделе «Мои заказы».');
  return strok.join('\n');
}

