export function mount(canvas: HTMLCanvasElement, host: HTMLElement): (() => void) | null {
  const gl = makeGL(canvas);
  if (!gl) return null; // WebGL нет — просто ничего не показываем

  const phone = window.matchMedia('(max-width: 640px)').matches;
  // Число пузырей — это плотность на ЭКРАНЕ, а не на странице.
  //
  // Прежние 19 жили в куске первого экрана 1348×504, из которого две
  // трети вычитали запретные прямоугольники. Теперь поле — всё окно
  // плюс запас, без запретов, и та же плотность даёт около тридцати.
  // Растить число вслед за ДЛИНОЙ страницы нельзя по двум причинам
  // сразу: массив uniform'ов uPos[N] + uRot[N] упирается в гарантию
  // WebGL (128 vec4 на вершинный шейдер, у нас на N = 30 уходит 68),
  // а точек стало бы вшестеро больше — за них платят кадрами.
  // Длину страницы отрабатывает не количество, а возвращение
  // пузыря с другой стороны полосы обитания.
  const COUNT = phone ? 16 : 30;
  /** Границы радиусов. Разброс широкий НАМЕРЕННО: пузыри одного
   *  калибра читаются россыпью одинаковых бусин, а не живым полем. */
  const R_MIN = phone ? 10 : 15;
  const R_MAX = phone ? 26 : 54;

  /** Точек на единицу площади оболочки. См. длинный разбор ниже,
   *  у объявления `counts`. */
  const KOL_NA_PLOSHAD = 0.15;

  /** Размер точки в зависимости от РАДИУСА её пузыря.
   *
   *  Прежде размер брался из одного отрезка 1.4–2.9 для всех пузырей
   *  сразу, и крупный шар выходил той же крупой, что и мелкий, —
   *  только крупы больше. Теперь у крупного пузыря точка крупнее,
   *  и разница размеров читается ещё и фактурой, а не одним силуэтом.
   *
   *  Корень, а не прямая: у прямой середина отрезка радиусов
   *  досталась бы мелким точкам (радиусы идут по логарифмической
   *  лесенке, и середина лесенки — это треть отрезка), и вся прибавка
   *  ушла бы в два самых крупных шара.
   *
   *  Возвращается размер ДО множителя глубины. На экране ближняя
   *  точка получается в 1.35 раза крупнее, дальняя вдвое мельче
   *  (`0.5 + 0.85 * near` в шейдере), поэтому 2.4–5.2 здесь — это
   *  3.2–7.0 px у ближней кромки против прежних 1.9–4.0. */
  const tochkaU = (r: number) => {
    const d = Math.sqrt(Math.max(0, (r - R_MIN) / (R_MAX - R_MIN)));
    return (phone ? 2.1 : 2.4) + (phone ? 2.0 : 2.8) * d;
  };

  const tanHalf = Math.tan((FOV / 2) * (Math.PI / 180));
  let proj = perspective(FOV, 1, 1, 4000);
  let view = viewAt(1);

  let w = 1;
  let h = 1;
  let dpr = 1;
  /** Разгон: первые секунды жизни модуля холст держится плотностью
   *  один, см. PLOTNOST_RAZGONA. */
  let razgon = true;
  /** Через сколько кадров на четвёртый рисуем: 1 — каждый, 2 — через
   *  один. Считается из размера буфера в `resize`. */
  let shag = 1;
  /** Сколько раз плотность уже понижена, см. `sledi`. */
  let ponizheno = 0;
  let camZ = 1;
  /** Полоса обитания в координатах СТРАНИЦЫ.
   *
   *  Холст закреплён по окну, а пузыри живут на странице: у каждого
   *  есть `py` — расстояние от верха документа вниз, в css-пикселях,
   *  как у `scrollY`. Полоса обитания — это окно плюс запас сверху
   *  и снизу; всё, что из неё вышло, возвращается с другой стороны.
   *  Так число пузырей не зависит от длины страницы, а плотность
   *  на экране одна и та же, где бы человек ни находился.
   *
   *  По горизонтали — всё окно: холст теперь во всю его ширину,
   *  и прятать пузыри от панели заказа больше незачем — они лежат
   *  ПОД ней. */
  let vis = { xmin: 0, xmax: 0, ymin: 0, ymax: 0 };
  /** Запас полосы обитания за кромкой окна, в пикселях. Должен быть
   *  заметно больше самого крупного радиуса: возвращение пузыря
   *  на другую сторону обязано случаться там, где его не видно. */
  const ZAPAS = 130;

  /** Прямоугольники бегущего текста в постраничных координатах.
   *
   *  Пузыри лежат ПОД содержимым, и краска на буквы не попадает —
   *  это проверено по пикселям (`check-bubbles`, проба «пузыри лежат
   *  под содержимым»: ноль точек тела штриха на всех заголовках).
   *  Но у текста, стоящего прямо на фоне страницы, фоном становится
   *  сам пузырь, а вместе с ним — и контраст.
   *
   *  Замер по настоящим пикселям, тёмная тема, самая плотная краска
   *  в окне 6×6: приглушённый текст даёт на ней 1.54:1 при пороге
   *  4.5, основной — 2.96. Плотность краски тут не спасает: при 1.2
   *  вместо 2.2 приглушённый поднимается только до 2.15. Причина
   *  устройственная — в сумерках краска СВЕТЛЕЕ фона и идёт навстречу
   *  светлому тексту.
   *
   *  Поэтому запрет остаётся, но не тот, что был. Прежний прятал
   *  краску от БУКВ, потому что холст лежал над фоном первого экрана;
   *  этот держит её от РАБОЧЕГО ТЕКСТА ради читаемости, и считается
   *  по всей странице. Всё остальное — поля, промежутки между
   *  блоками, места за непрозрачными карточками — пузырям открыто. */
  type Zapret = { top: number; bottom: number; left: number; right: number };
  let zaprety: Zapret[] = [];
  /** Запас вокруг текста в РАДИУСАХ пузыря. 1.15 значит: край
   *  оболочки может подойти к коробке текста на 0.15 радиуса, но
   *  не зайти в неё. Больше не нужно — краска до букв не доходит;
   *  меньше нельзя — оболочка отжимается курсором наружу. */
  const ZAPRET_KEEP = 1.15;
  /** Что считается рабочим текстом на фоне страницы. Плашки,
   *  карточки и чек сюда не входят: они непрозрачны, пузырь за ними
   *  не виден вовсе и контрасту не мешает. */
  const TEKST = '.hero__lead, .hero__title, .shop__title, .shop__lead, '
    + '.steps__title, .step__title, .step__text, .footer__title';
  /** Прокрутка на текущем кадре и высота документа. Читаются раз
   *  за кадр в начале такта. */
  let scrollTop = 0;
  let docH = 1;

  // ─── Пул пузырей ────────────────────────────────────────────
  const bubbles: Bubble[] = [];
  const queue: number[] = []; // время возвращения освободившегося места

  const spin = (b: Bubble) => {
    const dir = Math.random() * Math.PI * 2;
    b.vx = Math.cos(dir) * 5;
    b.vy = Math.sin(dir) * 5;
    b.dir = dir;
    b.speed = rnd(3.5, 7);
    b.pa = rnd(14, 22);
    b.pb = rnd(25, 37);
    b.swayA = rnd(0.22, 0.5);
    b.swayB = rnd(0.1, 0.28);
    b.wx = rnd(-0.16, 0.16);
    b.wy = rnd(0.12, 0.3) * (Math.random() < 0.5 ? -1 : 1);
    b.rx = Math.random() * 6.28;
    b.ry = Math.random() * 6.28;
    b.popped = 0;
    b.pop = 0;
    b.gone = false;
  };

  // Радиус берётся НЕ случайно из отрезка, а с лесенки: отрезок
  // [R_MIN, R_MAX] делится на COUNT логарифмических ступеней, и внутри
  // своей ступени радиус уже случаен. Иначе на каждой третьей загрузке
  // все двадцать два пузыря выпадали бы из середины отрезка и поле
  // снова читалось бы одинаковым. Лесенка логарифмическая, а не
  // равномерная: на глаз важно ОТНОШЕНИЕ размеров, и равномерный шаг
  // отдал бы половину ступеней крупным, где разница уже не видна.
  const stupen = Math.pow(R_MAX / R_MIN, 1 / COUNT);
  for (let i = 0; i < COUNT; i++) {
    const b: Bubble = {
      r: R_MIN * Math.pow(stupen, i + Math.random()),
      x: 0, y: 0, z: 0,
      vx: 0, vy: 0, dir: 0, speed: 0, pa: 1, pb: 1, swayA: 0, swayB: 0,
      rx: 0, ry: 0, wx: 0, wy: 0, popped: 0, pop: 0, gone: false,
    };
    spin(b);
    bubbles.push(b);
  }

  // ─── Геометрия: один объект на все пузыри, единичные сферы ───
  //
  // Точек — по ПЛОЩАДИ оболочки, а не по радиусу. Пока их было
  // пропорционально радиусу, плотность краски падала обратно
  // пропорционально ему: мелкий пузырь выходил плотным шариком,
  // крупный — редкой сеткой, и на широком разбросе размеров это
  // читалось как «большие недорисованы».
  //
  // Коэффициент 0.26 — это не «на глаз», а верхняя граница по кадрам.
  // Пузыри грузятся сразу после первой отрисовки, то есть попадают
  // ровно в окно, по которому считается время блокировки главного
  // потока. Замер под четырёхкратным замедлением процессора,
  // пять загрузок, медиана:
  //
  //   прежняя сборка ................................. 411 мс
  //   0.42, точки 1.9–4.0 ............................ 494 мс
  //   0.42, точки мельче (1.4–2.9) ................... 435 мс
  //   0.26, точки 1.9–4.0 ............................ 402 мс
  //
  // То есть платят ТОЧКИ, а не их размер. Крупные точки достаются
  // даром, число — нет.
  //
  // При этом плотность краски всё равно выше прежней на любом
  // радиусе: точки стали крупнее в полтора раза, и доля закрашенного
  // на оболочке выросла с 11.5 % до 17.9 % у мелкого пузыря
  // и с 6.9 % до 18 % у среднего.
  //
  // Коэффициент опущен с 0.26 до 0.15 ОДНОВРЕМЕННО с укрупнением
  // точки, и это не ослабление, а обмен по той же таблице. Краски
  // на оболочке столько же, сколько её кладут точки: доля
  // закрашенного считается как «число × площадь точки», то есть
  // c · s² с точностью до постоянной. Точка выросла в 1.8 раза
  // по стороне (в 3.2 по площади), значит при c = 0.15 краски
  // становится вдвое больше прежнего, а точек — вдвое меньше.
  // Платят точки; за размер не берут.
  const counts = bubbles.map((b) => Math.max(40, Math.round(b.r * b.r * KOL_NA_PLOSHAD)));
  const total = counts.reduce((a, n) => a + n, 0);
  const pos = new Float32Array(total * 3);
  const vel = new Float32Array(total * 3);
  const size = new Float32Array(total);
  const tint = new Float32Array(total);
  const phase = new Float32Array(total);
  const who = new Float32Array(total);

  let k = 0;
  bubbles.forEach((b, bi) => {
    const n = counts[bi];
    for (let i = 0; i < n; i++) {
      // Точки садятся на оболочку по спирали Фибоначчи, а не случайно:
      // случайные сбиваются в комки, и шар перестаёт читаться шаром.
      const y = 1 - (2 * i + 1) / n;
      const rad = Math.sqrt(Math.max(0, 1 - y * y));
      const th = i * 2.399963229728653; // золотой угол
      const jit = 1 + rnd(-0.035, 0.035); // иначе спираль видна узором
      const x = Math.cos(th) * rad;
      const z = Math.sin(th) * rad;
      pos[k * 3] = x * jit;
      pos[k * 3 + 1] = y * jit;
      pos[k * 3 + 2] = z * jit;

      const s = rnd(0.8, 1.9); // длина разлёта в долях радиуса
      vel[k * 3] = x * s;
      vel[k * 3 + 1] = y * s + rnd(0.06, 0.4);
      vel[k * 3 + 2] = z * s;

      size[k] = tochkaU(b.r) * rnd(0.86, 1.14);
      tint[k] = (Math.random() * 3) | 0;
      phase[k] = Math.random() * Math.PI * 2;
      who[k] = bi;
      k++;
    }
  });

  const program = makeProgram(gl, vert(COUNT), FRAG);
  if (!program) return null;
  gl.useProgram(program);

  const buffers = [
    staticAttrib(gl, program, 'position', pos, 3),
    staticAttrib(gl, program, 'aVel', vel, 3),
    staticAttrib(gl, program, 'aSize', size, 1),
    staticAttrib(gl, program, 'aTint', tint, 1),
    staticAttrib(gl, program, 'aPhase', phase, 1),
    staticAttrib(gl, program, 'aBubble', who, 1),
  ];

  const U = (name: string) => gl.getUniformLocation(program, name);
  const uSizeScale = U('uSizeScale');
  const uCamZ = U('uCamZ');
  const uPointerU = U('uPointer');
  const uPress = U('uPress');
  const uTime = U('uTime');
  const uInk = U('uInk');
  const uColorA = U('uColorA');
  const uColorB = U('uColorB');
  const uColorC = U('uColorC');
  const uPosU = U('uPos[0]');
  const uRotU = U('uRot[0]');
  const uProj = U('projectionMatrix');
  const uView = U('viewMatrix');

  // Точки полупрозрачны и лежат друг за другом: глубина не нужна,
  // смешивание — обычное «поверх».
  gl.disable(gl.DEPTH_TEST);
  gl.enable(gl.BLEND);
  gl.blendFuncSeparate(gl.SRC_ALPHA, gl.ONE_MINUS_SRC_ALPHA, gl.ONE, gl.ONE_MINUS_SRC_ALPHA);

  const posArr = new Float32Array(COUNT * 4);
  const rotArr = new Float32Array(COUNT * 4);

  // ─── Цвета из токенов ───────────────────────────────────────
  const readColors = () => {
    const cs = getComputedStyle(document.documentElement);
    gl.useProgram(program);
    gl.uniform1f(uInk, parseFloat(cs.getPropertyValue('--bubbles-ink')) || 1);
    const c = TOKENS.map((t) => readRgb(cs.getPropertyValue(t)));
    gl.uniform3fv(uColorA, c[0]);
    gl.uniform3fv(uColorB, c[1]);
    gl.uniform3fv(uColorC, c[2]);
  };

  /** Число целых пузырей — единственная наружная примета состояния:
   *  проверке иначе не за что зацепиться, а пиксели считать ненадёжно. */
  const publish = () => {
    const n = String(bubbles.filter((b) => !b.gone && !b.popped).length);
    if (canvas.dataset.bubbles !== n) canvas.dataset.bubbles = n;
  };

  // ─── Расстановка ────────────────────────────────────────────
  /** Ставит пузырь в свободное место полосы обитания: не вплотную
   *  к соседям и не туда, где только что лопнул предыдущий.
   *
   *  `storona` задаёт, с какой стороны пузырь входит в полосу.
   *  Возвращение обязано случаться там, где его не видно, поэтому
   *  вошедший сверху ставится в верхний запас полосы, вошедший
   *  снизу — в нижний. Без стороны место ищется по всей полосе:
   *  так расставляются пузыри при запуске и возвращаются лопнувшие. */
  const place = (b: Bubble, avoid?: { x: number; y: number }, storona?: 'sverhu' | 'snizu') => {
    // Координата ПОСТРАНИЧНАЯ и направлена вверх: y = −(отступ от
    // верха документа). Верх полосы — это её наибольший y.
    const lo = storona === 'sverhu' ? vis.ymax - ZAPAS * 0.8 : storona === 'snizu' ? vis.ymin - b.r : vis.ymin + b.r * EDGE;
    const hi = storona === 'sverhu' ? vis.ymax + b.r : storona === 'snizu' ? vis.ymin + ZAPAS * 0.8 : vis.ymax - b.r * EDGE;
    for (let i = 0; i < 40; i++) {
      const x = rnd(vis.xmin + b.r * EDGE, vis.xmax - b.r * EDGE);
      const y = rnd(lo, hi);
      if (vZaprete(x, y, b.r)) continue;
      if (avoid && Math.hypot(x - avoid.x, y - avoid.y) < 140) continue;
      // Не вплотную к уже стоящим: иначе десяток шаров ставится
      // в кучу и первые секунды они разбираются друг с другом.
      let near = false;
      for (const o of bubbles) {
        if (o === b || o.gone) continue;
        if (Math.hypot(x - o.x, y - o.y) < (b.r + o.r) * 1.25) { near = true; break; }
      }
      if (near && i < 14) continue;
      b.x = x;
      b.y = y;
      b.z = rnd(-b.r * 0.5, b.r * 0.5);
      return;
    }
    // Место не нашлось за сорок попыток — ставим как выпало.
    b.x = rnd(vis.xmin + b.r * EDGE, vis.xmax - b.r * EDGE);
    b.y = rnd(lo, hi);
    b.z = 0;
  };

  /** Пересчитать прямоугольники текста. Дорого (чтение геометрии
   *  десятка узлов), поэтому только на изменение размеров, а не
   *  каждый кадр: относительно СТРАНИЦЫ текст не двигается. */
  const zameritTekst = () => {
    const sy = window.scrollY;
    const pad = 6;
    zaprety = [...document.querySelectorAll(TEKST)].map((el) => {
      const b = el.getBoundingClientRect();
      if (b.width < 4 || b.height < 4) return null;
      // Постраничные координаты: +y вверх, ноль у верха документа.
      return {
        top: -(b.top + sy) + pad,
        bottom: -(b.bottom + sy) - pad,
        left: b.left - w / 2 - pad,
        right: b.right - w / 2 + pad,
      };
    }).filter(Boolean) as Zapret[];
  };

  /** Накрывает ли пузырь запретный прямоугольник. */
  const vZaprete = (x: number, y: number, r: number) => {
    const keep = r * ZAPRET_KEEP;
    for (const q of zaprety) {
      if (x > q.left - keep && x < q.right + keep && y - keep < q.top && y + keep > q.bottom) return true;
    }
    return false;
  };

  /** Полоса обитания в постраничных координатах (+y вверх, ноль
   *  у верха документа). Пересчитывается каждый кадр: она едет
   *  вместе с прокруткой. */
  const polosa = () => {
    vis = {
      xmin: -w / 2,
      xmax: w / 2,
      ymin: -(scrollTop + h + ZAPAS),
      ymax: -(scrollTop - ZAPAS),
    };
  };

  const resize = () => {
    // Холст закреплён по ОКНУ: position: fixed, inset: 0. Размеры
    // всё равно ставит скрипт, а не CSS, — canvas заменяемый элемент
    // и при width: auto берёт своё собственное 300×150, а не
    // расстояние между кромками.
    //
    // Слой во всю ширину окна раньше отвергали по замеру кадров.
    // Теперь платить за него нечем: точек стало вдвое меньше
    // (см. KOL_NA_PLOSHAD), а сам слой по-прежнему размером
    // ровно в окно — при холсте во всю ВЫСОТУ СТРАНИЦЫ он был бы
    // втрое больше и композитился бы целиком.
    w = Math.max(1, Math.round(window.innerWidth));
    h = Math.max(1, Math.round(window.innerHeight));
    canvas.style.width = `${w}px`;
    canvas.style.height = `${h}px`;
    // Геометрия задана — можно показывать. До этого момента холст
    // скрыт, иначе его переезд из 300×150 в углу засчитывается
    // сдвигом вёрстки.
    canvas.style.visibility = 'visible';
    // Плотность холста — ПОЛНАЯ, и это правка того, что было сделано
    // неверно.
    //
    // Здесь стоял бюджет в 300 тысяч пикселей на буфер: он держал
    // кадры, но на 1512×900 давал плотность 0.47, то есть буфер
    // 710×423 на окно шириной 1512. Точка пузыря шириной 3.2 css-px
    // занимала при этом ПОЛТОРА отсчёта буфера. Круглым пятном
    // полтора отсчёта не бывают: точка вырождалась в квадратик,
    // растягивалась обратно вдвое и читалась крупой. Замер по
    // увеличенному снимку: округлость 0.87 при 1.00 у круга.
    //
    // Крупные точки, сделанные тем же заходом, беду не создали,
    // а проявили: в БУФЕРЕ точка стала мельче прежней (1.5 отсчёта
    // против 1.9), а на ЭКРАНЕ вдвое крупнее — то есть тот же
    // квадратик показали в увеличении.
    //
    // Поэтому плотность теперь равна плотности экрана. Выше двух
    // не поднимаем: разницы не видно, а платить приходится вчетверо.
    // Потолок в 9 млн пикселей (36 МБ) — только чтобы 4K не съел
    // память; на окнах до 2560×1440 он не срабатывает вовсе.
    const ustupka = ponizheno > 0 ? LESENKA[ponizheno - 1] : null;
    dpr = Math.min(window.devicePixelRatio || 1, razgon ? PLOTNOST_RAZGONA : PLOTNOST_MAX,
      Math.sqrt(POTOLOK / (w * h))) * (ustupka ? ustupka.plotnost : 1);

    // Чем платим. Каждый кадр содержимое холста уезжает к композитору
    // целиком, и на машине без ускорителя это стоит около 12,5 нс
    // на пиксель буфера. Замер по частям: холст, оставленный РИСОВАТЬ,
    // но убранный из отрисовки, не стоит ничего (0.0 %), и холст,
    // который отрисовывается, но не перерисовывается, тоже (0.0 %).
    // Платит именно ВЫГРУЗКА СВЕЖЕГО буфера.
    //
    // Отсюда шаг: буфер крупнее порога рисуется ЧЕРЕЗ КАДР. Картинка
    // едет вдвое реже, но страница остаётся на 60 fps — а это и есть
    // то, что видит человек. Замер на 1512×900 при полной плотности:
    // каждый кадр — 16.6 % кадров дольше 17 мс, через кадр — 0.0 %.
    // На 1920×1080 — 48.8 % против 3.4 %.
    //
    // Дальше двух шаг не растёт: на 2560×1440 одна выгрузка не
    // укладывается в кадр вовсе, и каждый третий (47.5 %) с каждым
    // четвёртым (33.5 %) её не спасают. Там работает не шаг,
    // а понижение плотности — см. `sledi` ниже.
    const tsena = w * h * (dpr * dpr + Math.pow(window.devicePixelRatio || 1, 2));
    shag = (tsena <= TSENA_SHAG_1 ? 1 : tsena <= TSENA_SHAG_2 ? 2 : 3) + (ustupka ? ustupka.shag : 0);
    // Камера отодвинута так, что на плоскости z = 0 единица мира —
    // ровно один css-пиксель. Тогда радиусы и размеры точек задаются
    // в пикселях и не зависят от размера окна.
    camZ = h / 2 / tanHalf;
    proj = perspective(FOV, w / h, 1, 4000);
    view = viewAt(camZ);
    canvas.width = Math.round(w * dpr);
    canvas.height = Math.round(h * dpr);
    gl.viewport(0, 0, canvas.width, canvas.height);
    gl.useProgram(program);
    gl.uniformMatrix4fv(uProj, false, proj);
    gl.uniformMatrix4fv(uView, false, view);
    gl.uniform1f(uSizeScale, dpr * camZ);
    gl.uniform1f(uCamZ, camZ);
    // Наружу — чтобы проверка мерила то, что есть, а не то, что
    // должно было получиться по формуле.
    canvas.dataset.plotnost = dpr.toFixed(2);
    canvas.dataset.shag = String(shag);
    canvas.dataset.ustupok = String(ponizheno);
    scrollTop = window.scrollY;
    docH = Math.max(h, document.documentElement.scrollHeight);
    zameritTekst();
    polosa();
    for (const b of bubbles) {
      b.x = Math.max(vis.xmin + b.r * EDGE, Math.min(vis.xmax - b.r * EDGE, b.x));
      b.y = Math.max(vis.ymin + b.r * EDGE, Math.min(vis.ymax - b.r * EDGE, b.y));
    }
  };

  resize();
  readColors();
  for (const b of bubbles) place(b);
  publish();

  // ─── Курсор ─────────────────────────────────────────────────
  // Слой мышь не ловит (pointer-events: none), поэтому положение
  // курсора слушается НА ОКНЕ и переводится в координаты сцены,
  // а попадание по пузырю считается вручную.
  //
  // Слушать окно, а не секцию, обязательно. Холст выходит из колонки
  // ВЛЕВО до кромки окна, и та его часть лежит уже не над секцией:
  // события туда не доходили вовсе, и примерно пятая часть поля была
  // мёртвой — пузыри там не отзывались ни на что. Замер по сетке
  // точек показывал 84 мёртвые пробы из 468. С окном мёртвых зон
  // не бывает по построению: нет элемента, чьи границы могли бы
  // не совпасть с границами поля.
  //
  // Курсоров ДВА, и это не дублирование.
  //
  // `pointer` — сырой, без сглаживания вовсе: он уходит в шейдер,
  // и оболочка обязана идти прямо за курсором. Прежде сюда шла
  // сглаженная позиция с постоянной около 150 мс, и отклик заметно
  // отставал от руки.
  //
  // `pointerSoft` — сглаженный, и только для сдвига пузыря ЦЕЛИКОМ.
  // Эту силу дёргать нельзя: пузырь, скачками уезжающий от курсора,
  // невозможно поймать.
  const pointer = vec(1e5, 1e5, 0);
  const pointerSoft = vec(1e5, 1e5, 0);
  /** Стоит ли сейчас указатель. Держим сами, чтобы не переписывать
   *  инлайновый стиль на каждом движении мыши. */
  let ukazatel = false;
  /** Когда последний раз считали, свободна ли точка под курсором. */
  let proverenoV = -1e9;
  let press = 0;
  let pressTo = 0;
  /** Экспоненциальное приближение с постоянной времени в секундах. */
  const toward = (cur: number, aim: number, tau: number, dt: number) =>
    cur + (aim - cur) * (1 - Math.exp(-dt / tau));

  /** Курсор в двух системах отсчёта сразу: мировая уходит в шейдер,
   *  постраничная — в поиск попадания по пузырю. */
  const toWorld = (e: PointerEvent) => {
    const rect = canvas.getBoundingClientRect();
    const x = e.clientX - rect.left - w / 2;
    const y = h / 2 - (e.clientY - rect.top);
    return { x, y, py: y - (window.scrollY + h / 2) };
  };

  /** Курсор над самим полем — независимо от того, что лежит сверху. */
  const inField = (e: PointerEvent) => {
    const r = canvas.getBoundingClientRect();
    return e.clientX >= r.left && e.clientX <= r.right
        && e.clientY >= r.top && e.clientY <= r.bottom;
  };

  const INTERACTIVE = 'a, button, input, label, summary, [role="button"], [data-lenis-scrollable]';

  /** Свободна ли точка — то есть виден ли в ней сам фон страницы.
   *
   *  Пузыри лежат под всем содержимым, и приоритет над ними всегда
   *  у интерфейса: над кнопкой, ссылкой, карточкой или чеком нажатие
   *  достаётся им, а не пузырю. Список селекторов для этого не годится
   *  — он устареет на первой же новой карточке. Признак берётся
   *  общий: над точкой не должно быть НИ ОДНОГО непрозрачного слоя.
   *
   *  `elementsFromPoint` отдаёт стопку сверху вниз; для каждого
   *  элемента смотрим его собственную заливку. Непрозрачный фон
   *  или картинка-градиент — значит пузырь за ним не виден, и щёлкать
   *  по невидимому нельзя. Корень и body пропускаем: их заливка —
   *  это и есть фон страницы, он лежит ПОД холстом.
   *
   *  Стоит это одного `elementsFromPoint` на нажатие и на движение
   *  мыши — сотые доли миллисекунды, и только когда курсор в поле. */
  const svobodno = (cx: number, cy: number) => {
    const stopka = document.elementsFromPoint(cx, cy);
    for (const el of stopka) {
      if (el === document.body || el === document.documentElement) break;
      if (el === canvas) continue;
      const cs = getComputedStyle(el);
      if (cs.backgroundImage !== 'none') return false;
      const bg = cs.backgroundColor;
      if (bg && bg !== 'transparent' && !/rgba\(\s*0\s*,\s*0\s*,\s*0\s*,\s*0\s*\)/.test(bg)) {
        const m = bg.match(/[\d.]+/g);
        if (!m || m.length < 4 || Number(m[3]) > 0.05) return false;
      }
    }
    return true;
  };

  const hitTest = (x: number, y: number) => {
    let best: Bubble | null = null;
    let bd = Infinity;
    for (const b of bubbles) {
      if (b.gone || b.popped) continue;
      const d = Math.hypot(x - b.x, y - b.y);
      if (d < b.r * 1.05 && d < bd) { bd = d; best = b; }
    }
    return best;
  };

  const onMove = (e: PointerEvent) => {
    if (!inField(e)) { onLeave(); return; }
    const { x, y, py } = toWorld(e);
    pointer.x = x; pointer.y = y;
    if (pointerSoft.x > 5e4) { pointerSoft.x = pointer.x; pointerSoft.y = pointer.y; }
    pressTo = 1;
    // Указатель ставится только там, где пузырь ВИДЕН и по нему
    // можно щёлкнуть: над непрозрачным содержимым нажатие всё равно
    // достанется ему, и обещать пальцем несуществующее нельзя.
    //
    // Дорогая половина проверки (`svobodno` — это elementsFromPoint
    // и разбор стилей) считается не на каждом движении мыши, а не
    // чаще раза в 120 мс: курсор шевелится по событию на каждый кадр,
    // а стопка элементов под ним за один кадр не меняется.
    const pop = hitTest(x, py);
    const teper = performance.now();
    if (!pop) { if (ukazatel) { ukazatel = false; host.style.cursor = ''; } return; }
    if (teper - proverenoV < 120 && ukazatel) return;
    proverenoV = teper;
    const nado = svobodno(e.clientX, e.clientY);
    if (nado !== ukazatel) {
      ukazatel = nado;
      host.style.cursor = nado ? 'pointer' : '';
    }
  };

  const onLeave = () => {
    // Позицию НЕ уводим в бесконечность сразу: оболочка должна
    // разгладиться плавно, а не отпустить скачком. Курсор паркуется
    // сам, когда нажим доедет до нуля.
    pressTo = 0;
    ukazatel = false;
    host.style.cursor = '';
  };

  const onDown = (e: PointerEvent) => {
    if (!inField(e)) return;
    const el = e.target as HTMLElement | null;
    if (el?.closest(INTERACTIVE)) return;
    const { x, y, py } = toWorld(e);
    // На касании курсора нет, поэтому реакцию оболочки запускает само
    // касание: палец ведут — пузыри проминаются, как под мышью.
    pointer.x = x; pointer.y = y;
    if (pointerSoft.x > 5e4) { pointerSoft.x = pointer.x; pointerSoft.y = pointer.y; }
    pressTo = 1;
    const hit = hitTest(x, py);
    if (!hit) return;
    // Над непрозрачным содержимым пузырь не виден — значит и лопать
    // нечего: приоритет у интерфейса. Проверка стоит ПОСЛЕ поиска
    // попадания, чтобы не платить за неё на каждом нажатии мимо.
    if (!svobodno(e.clientX, e.clientY)) return;
    hit.popped = gsap.ticker.time * 1000;
    ukazatel = false;
    host.style.cursor = '';
    publish();
  };

  // Палец, в отличие от курсора, уходит со стекла совсем: без этого
  // нажим, поднятый касанием, остался бы поднятым навсегда.
  const onUp = (e: PointerEvent) => { if (e.pointerType !== 'mouse') onLeave(); };

  window.addEventListener('pointermove', onMove, { passive: true });
  window.addEventListener('pointerdown', onDown, { passive: true });
  window.addEventListener('pointerup', onUp, { passive: true });
  window.addEventListener('pointercancel', onUp, { passive: true });
  // Курсор ушёл из окна совсем — оболочка разглаживается.
  document.addEventListener('pointerleave', onLeave, { passive: true });

  // ─── Такт ───────────────────────────────────────────────────
  //
  // Наблюдателя за видимостью больше нет и быть не может: холст
  // закреплён по окну и виден всегда. Прежний IntersectionObserver
  // гасил такт, когда первый экран уезжал, — теперь гасить нечего.
  // За вкладкой, ушедшей в фон, следит сам браузер: requestAnimationFrame
  // там не вызывается, а тикер GSAP сидит на нём.

  // Цвета читаются не каждый кадр: чтение переменной с корня — это
  // пересчёт стиля. В покое не читаем вовсе, а на смену темы открываем
  // короткое окно и в нём перечитываем часто, чтобы пузыри доехали
  // до нового цвета вместе со страницей.
  let colorWindow = 0;
  const mo = new MutationObserver(() => { colorWindow = gsap.ticker.time * 1000 + 700; });
  mo.observe(document.documentElement, { attributes: true, attributeFilter: ['data-theme'] });

  let prev = 0;
  let frames = 0;
  /** Номер кадра для шага отрисовки. */
  let kadr = 0;

  // ─── Присмотр за кадрами ─────────────────────────────────────
  //
  // Шаг отрисовки выведен из размера буфера, а размер буфера —
  // из размера окна. Но цена пикселя зависит от МАШИНЫ: там, где
  // есть ускоритель, слой во весь экран не стоит ничего, а там, где
  // его нет, 2560×1440 не укладывается в кадр ни при каком шаге
  // (замерено: каждый третий кадр — 47.5 % кадров дольше 17 мс,
  // каждый четвёртый — 33.5 %).
  //
  // Поэтому окно и шаг задают НАЧАЛЬНОЕ качество, а дальше смотрим,
  // тянет ли машина. Не тянет — понижаем плотность на четверть.
  // Обратно не поднимаем: машина не станет быстрее, а качели между
  // двумя плотностями заметнее, чем любая из них.
  //
  // Два подряд плохих окна, а не одно: смена темы, разворот карточки
  // витрины и первая прокрутка дают всплеск длинных кадров, за
  // который пузыри не в ответе.
  let oknoDo = 0;
  let vOkne = 0;
  let podryad = 0;
  /** Метка запуска модуля. Тикер GSAP заводится вместе со страницей,
   *  а пузыри поднимаются позже — и насколько позже, зависит от сети
   *  и от машины. Отсчёт от нуля тикера означал бы, что на медленной
   *  загрузке разгон кончается раньше, чем начинается. */
  let pusk = 0;
  const sledi = (t: number) => {
    if (!pusk) pusk = t;
    const ot = t - pusk;
    if (razgon && ot >= NACHALO_MS) { razgon = false; resize(); }
    if (ponizheno >= LESENKA.length) return;
    // Первые секунды не в счёт: страница ещё доезжает — поднимается
    // Lenis, доигрывают появления блоков, доходят шрифты. И плотность
    // в это время ещё разгонная, судить по ней нечего.
    if (ot < NACHALO_MS) return;
    if (!oknoDo) { oknoDo = t + OKNO_MS; return; }
    vOkne++;
    if (t < oknoDo) return;
    // Сколько кадров ДОЛЖНО было прийти за это окно и сколько пришло.
    const dolzhno = OKNO_MS / KADR_MS;
    const ploho = 1 - vOkne / dolzhno > DOLYA_PLOHIH;
    oknoDo = t + OKNO_MS;
    vOkne = 0;
    podryad = ploho ? podryad + 1 : 0;
    // Первая уступка — только после ДВУХ плохих окон подряд: смена
    // темы, разворот карточки витрины и первая прокрутка дают всплеск
    // длинных кадров, за который пузыри не в ответе. Дальше хватает
    // одного окна: машина себя уже показала, и тянуть ещё полторы
    // секунды видимой рвани незачем.
    if (podryad < (ponizheno === 0 ? 2 : 1)) return;
    podryad = 0;
    ponizheno++;
    resize();
  };

  const step = (time: number) => {
    const t = time * 1000;
    const dt = prev ? Math.min(0.05, (t - prev) / 1000) : 0;
    prev = t;

    if (t < colorWindow && (frames & 3) === 0) readColors();
    frames++;

    // Прокрутка читается РАЗ ЗА КАДР и только здесь. Пузыри живут
    // на странице, холст закреплён по окну, и весь переезд одного
    // в другое — это одно число.
    const bylo = scrollTop;
    scrollTop = window.scrollY;
    // Скачок — это переход по ссылке-якорю, End, Home или бросок
    // полосой прокрутки. Обычная прокрутка сдвигает полосу обитания
    // на десятки пикселей за кадр, и вышедший пузырь возвращается
    // в запас у ВХОДЯЩЕЙ кромки: страница везёт его в кадр сама.
    // При скачке везти некому — все тридцать разом оказались бы
    // в узкой полоске за кромкой и минуту всплывали бы в кадр
    // со скоростью пять пикселей в секунду. Поэтому после скачка
    // место ищется по всей полосе: картинка на экране всё равно
    // сменилась целиком, и подмены не видно.
    const skachok = Math.abs(scrollTop - bylo) > h * 0.5;
    polosa();

    // Нажим набирается почти мгновенно (35 мс) и отпускает медленно
    // (220 мс): пока курсор рядом, оболочка держится промятой, ушёл —
    // плавно возвращается. Раньше обе стороны шли по 250 мс, и вход
    // в реакцию отставал от руки ровно настолько, чтобы это читалось
    // запаздыванием.
    press = toward(press, pressTo, pressTo > press ? 0.035 : 0.22, dt);
    // Сглаженный курсор — только для сдвига пузыря целиком.
    if (pressTo > 0) {
      pointerSoft.x = toward(pointerSoft.x, pointer.x, 0.12, dt);
      pointerSoft.y = toward(pointerSoft.y, pointer.y, 0.12, dt);
    }
    // Отпустили и разгладилось — курсор уходит с поля.
    if (pressTo === 0 && press < 0.002) {
      pointer.x = 1e5; pointer.y = 1e5;
      pointerSoft.x = 1e5; pointerSoft.y = 1e5;
    }
    gl.useProgram(program);
    gl.uniform1f(uTime, t / 1000);
    gl.uniform3f(uPointerU, pointer.x, pointer.y, pointer.z);
    gl.uniform1f(uPress, press);

    // Переезд между двумя системами отсчёта, и он ровно один.
    //
    //   мировая     — то, что видит шейдер: ноль в середине ОКНА, +y вверх;
    //   постраничная — то, в чём живут пузыри: ноль у верха ДОКУМЕНТА, +y вверх.
    //
    // Одна получается из другой сдвигом на `sdvig`. Курсор приходит
    // в мировой (он и есть событие окна), поэтому для физики его
    // переводят сюда, а положения пузырей переводят обратно перед
    // записью в uniform. Больше нигде две системы не встречаются —
    // именно поэтому в физике ниже не пришлось трогать ни одного знака.
    const sdvig = scrollTop + h / 2;
    const pSoftY = pointerSoft.y - sdvig;

    for (let i = 0; i < bubbles.length; i++) {
      const b = bubbles[i];

      if (b.popped) {
        b.pop = Math.min(1, (t - b.popped) / POP_MS);
        if (b.pop >= 1) {
          b.gone = true;
          b.popped = 0;
          queue.push(t + rnd(RESPAWN_MIN, RESPAWN_MAX));
        }
      }

      if (!b.gone && !b.popped) {
        // Ход: направление качается двумя синусами с некратными
        // периодами. Случайность в направлении читалась бы дрожью.
        const ang = b.dir + Math.sin(t / 1000 / b.pa) * b.swayA + Math.sin(t / 1000 / b.pb) * b.swayB;
        const tx = Math.cos(ang) * b.speed;
        const ty = Math.sin(ang) * b.speed;

        // Отталкивание от курсора — у всего пузыря, но слабое и КОЛЬЦОМ:
        // ноль в самом центре, наибольшее примерно в полутора радиусах,
        // снова ноль дальше. Так курсор, проходящий рядом, подталкивает
        // пузырь, а курсор, наведённый прямо на него, не выталкивает
        // его из-под себя — иначе по пузырю невозможно попасть, и вся
        // затея с «увидел отклик — щёлкнул» рассыпается.
        const dx = b.x - pointerSoft.x;
        const dy = b.y - pSoftY;
        const dd = Math.hypot(dx, dy);
        if (dd < b.r * 3.2 && dd > 0.001) {
          const kk = Math.sin(Math.PI * (dd / (b.r * 3.2))) * press * 16;
          b.vx += ((dx / dd) * kk - 0) * Math.min(1, dt * 1.6);
          b.vy += ((dy / dd) * kk - 0) * Math.min(1, dt * 1.6);
        }

        // Инерция: скорость догоняет цель, а не подменяется ею.
        b.vx += (tx - b.vx) * Math.min(1, dt * 1.6);
        b.vy += (ty - b.vy) * Math.min(1, dt * 1.6);

        // Расталкивание соседей. Пузырей стало вдвое больше, и без
        // него они слипаются в комки: два наложившихся шара читаются
        // одним мятым пятном, а не двумя объёмами. Сила слабая
        // и работает только вплотную — это не бильярд, а взаимное
        // уважение. Каждая пара считается один раз.
        for (let j = i + 1; j < bubbles.length; j++) {
          const o = bubbles[j];
          if (o.gone || o.popped) continue;
          const ox = b.x - o.x;
          const oy = b.y - o.y;
          const od = Math.hypot(ox, oy);
          const want = (b.r + o.r) * 1.65;
          if (od > want || od < 0.001) continue;
          const push = (1 - od / want) * 58 * dt;
          b.vx += (ox / od) * push;
          b.vy += (oy / od) * push;
          o.vx -= (ox / od) * push;
          o.vy -= (oy / od) * push;
        }

        b.x += b.vx * dt;
        b.y += b.vy * dt;
        b.ry += b.wy * dt;
        b.rx += b.wx * dt;

        // Мягкий отскок от кромок кадра.
        // Разворот происходит НА РАССТОЯНИИ от края, а не у самого
        // края. Запас — радиус плюс то, на что оболочку отжимает
        // курсор: иначе под блоками условий видна прямая линия,
        // на которой пузыри срезаются кромкой холста. Кромка должна
        // не читаться вовсе, а для этого до неё нельзя доходить.
        const k6 = b.r * EDGE;
        if (b.x < vis.xmin + k6) { b.x = vis.xmin + k6; b.dir = Math.PI - b.dir; b.vx = Math.abs(b.vx); }
        if (b.x > vis.xmax - k6) { b.x = vis.xmax - k6; b.dir = Math.PI - b.dir; b.vx = -Math.abs(b.vx); }
        // По вертикали кромки нет: полоса обитания едет вместе
        // с прокруткой, и пузырь, оставшийся позади, ВОЗВРАЩАЕТСЯ
        // с другой стороны, а не отскакивает.
        //
        // Это и есть ответ на «пузыри по всей странице»: их число
        // не зависит от её длины, плотность на экране всюду одна
        // и та же, а рисуется только то, что рядом с окном.
        // Возвращение случается за кромкой полосы, то есть за
        // пределами видимого, — увидеть его нельзя.
        //
        // У краёв документа полоса упирается в него: у самого верха
        // страницы возвращать пузырь наверх некуда, и он остаётся
        // там, где есть, пока человек не прокрутит.
        if (b.y > vis.ymax && -vis.ymax > 0) { spin(b); place(b, undefined, skachok ? undefined : 'snizu'); }
        else if (b.y < vis.ymin && -vis.ymin < docH) { spin(b); place(b, undefined, skachok ? undefined : 'sverhu'); }
        else {
          if (b.y > vis.ymax - k6 && -vis.ymax <= 0) { b.y = vis.ymax - k6; b.dir = -b.dir; b.vy = -Math.abs(b.vy); }
          if (b.y < vis.ymin + k6 && -vis.ymin >= docH) { b.y = vis.ymin + k6; b.dir = -b.dir; b.vy = Math.abs(b.vy); }
        }

        // Выталкивание из-под рабочего текста. Причина не в том, что
        // краска попадёт на буквы — не попадёт, слой лежит ниже, —
        // а в том, что для текста на фоне страницы пузырь СТАНОВИТСЯ
        // фоном. Числа в объявлении `zaprety`.
        //
        // Проход повторяется трижды: прямоугольники стоят один под
        // другим (заголовок раздела, подзаголовок, три колонки шагов),
        // и выталкивание из нижнего заносит пузырь в верхний. Верхний
        // в этом кадре уже разобран, поправка пришла бы только
        // на следующем — и на один кадр краска оказывается под
        // строкой.
        for (let pass = 0; pass < 3; pass++)
        for (const q of zaprety) {
          const keep = b.r * ZAPRET_KEEP;
          const top = q.top + keep;
          const bot = q.bottom - keep;
          if (b.x < q.left - keep || b.x > q.right + keep) continue;
          if (b.y >= top || b.y <= bot) continue;
          // Выталкиваем к ближайшей стороне, в том числе вбок:
          // прямоугольник строки узкий по высоте и широкий по ширине,
          // и выход через бок часто ближе.
          const dTop = top - b.y;
          const dBot = b.y - bot;
          const dLeft = b.x - (q.left - keep);
          const dRight = q.right + keep - b.x;
          const m = Math.min(dTop, dBot, dLeft, dRight);
          if (m === dTop) { b.y = top; b.vy = Math.abs(b.vy); b.dir = -b.dir; }
          else if (m === dBot) { b.y = bot; b.vy = -Math.abs(b.vy); b.dir = -b.dir; }
          else if (m === dLeft) { b.x = q.left - keep; b.vx = -Math.abs(b.vx); b.dir = Math.PI - b.dir; }
          else { b.x = q.right + keep; b.vx = Math.abs(b.vx); b.dir = Math.PI - b.dir; }
        }
      }

      const o4 = i * 4;
      posArr[o4] = b.x;
      posArr[o4 + 1] = b.y + sdvig;   // постраничная → мировая
      posArr[o4 + 2] = b.z;
      // Пустое место прячем нулевым радиусом: точки схлопываются
      // в центр и гаснут прозрачностью через pop = 1.
      posArr[o4 + 3] = b.gone ? 0.0001 : b.r;
      rotArr[o4] = b.rx;
      rotArr[o4 + 1] = b.ry;
      rotArr[o4 + 2] = b.gone ? 1 : b.pop;
      rotArr[o4 + 3] = 0;
    }

    // Освободившиеся места возвращаются через паузу: число держится.
    for (let i = queue.length - 1; i >= 0; i--) {
      if (t < queue[i]) continue;
      queue.splice(i, 1);
      const free = bubbles.find((b) => b.gone);
      if (!free) continue;
      spin(free);
      place(free, { x: pointerSoft.x, y: pSoftY });
    }
    publish();

    sledi(t);
    if (shag > 1 && kadr++ % shag) return;

    gl.uniform4fv(uPosU, posArr);
    gl.uniform4fv(uRotU, rotArr);
    gl.clearColor(0, 0, 0, 0);
    gl.clear(gl.COLOR_BUFFER_BIT);
    gl.drawArrays(gl.POINTS, 0, total);
  };

  gsap.ticker.add(step);

  // Холст закреплён по окну, поэтому пересчёт нужен на изменение
  // ОКНА, а не секции. ResizeObserver на body остаётся ради второго
  // числа — высоты документа: она меняется, когда раскрывается
  // карточка витрины, и от неё зависит, где полоса обитания упирается
  // в конец страницы.
  const onResize = () => resize();
  window.addEventListener('resize', onResize, { passive: true });
  const ro = new ResizeObserver(() => {
    docH = Math.max(h, document.documentElement.scrollHeight);
    zameritTekst();
  });
  ro.observe(document.body);

  const onLost = (e: Event) => {
    e.preventDefault();
    gsap.ticker.remove(step);
    canvas.remove();
  };
  canvas.addEventListener('webglcontextlost', onLost);

  return () => {
    gsap.ticker.remove(step);
    window.removeEventListener('pointermove', onMove);
    window.removeEventListener('pointerdown', onDown);
    window.removeEventListener('pointerup', onUp);
    window.removeEventListener('pointercancel', onUp);
    document.removeEventListener('pointerleave', onLeave);
    window.removeEventListener('resize', onResize);
    canvas.removeEventListener('webglcontextlost', onLost);
    ro.disconnect();
    mo.disconnect();
    host.style.cursor = '';
    for (const b of buffers) if (b) gl.deleteBuffer(b);
    gl.deleteProgram(program);
    const lose = gl.getExtension('WEBGL_lose_context');
    lose?.loseContext();
  };
}
