/**
 * Счётчик подписок в шапке: живое число вместо зашитого.
 *
 * Строка «Уже N пользователей оформили подписки» много месяцев
 * держала одно и то же число: сайт статический, и другого способа
 * у него не было. Теперь способ тот же, что у промокода и у вопроса
 * «оплачен ли мой заказ», — сайт СПРАШИВАЕТ бота.
 *
 * СКЛАДЫВАЕТ ЗДЕСЬ, А НЕ В БОТЕ, и это решение. Бот отдаёт голый
 * факт — сколько заказов выдано; засев (`catalog.subscribers`) лежит
 * в каталоге сайта и здесь же служит запасным значением. Сложи мы
 * в боте — засев пришлось бы держать вторым экземпляром на сервере,
 * и два числа разъехались бы молча при первой же правке одного
 * из них.
 *
 * НЕОТВЕТ — ЭТО ЗАСЕВ, А НЕ НОЛЬ И НЕ ПУСТОТА. Бот может молчать
 * по десятку причин: не прогнали `server-setup.sh` и путь отвечает
 * 404, бот перезапускается выкладкой, сеть моргнула. Ни одна из них
 * не повод показать человеку «Уже 0 пользователей» или пустое место
 * в шапке — число рисуется сразу, из сборки, и лишь потом тихо
 * уточняется.
 *
 * СПРАШИВАЕТСЯ ОДИН РАЗ ЗА ЗАГРУЗКУ. Лавка ручная, выдача идёт
 * руками помощника — между двумя выдачами проходят минуты, а то
 * и часы. Повторять вопрос по таймеру значило бы изображать
 * происходящий прямо сейчас рост, а это ровно то, что запрещает
 * раздел «Доверие в оформлении»: число — факт, движение вокруг
 * него — подгонялка.
 */

import { useEffect, useState } from 'react';

/**
 * Откуда начинается разбег числа в шапке.
 *
 * НОЛЬ, И ЭТО ЕДИНСТВЕННОЕ ЧЕСТНОЕ НАЧАЛО. Любое другое маленькое
 * число — «120», «800» — это утверждение: застынь кадр, и человек
 * прочтёт его как настоящее количество подписок. У нуля такого
 * прочтения нет: счёт с нуля читается счётом, а не заявлением.
 *
 * Застыть ему при этом негде. Пока разбег не сделал ПЕРВОГО кадра,
 * узел разбега пуст, и в шапке видно настоящее число из разметки
 * (`.nav__counter-run:not(:empty)` в nav.css). То есть ноль на экран
 * не попадает вовсе: первый же кадр уже выше него.
 */
export const NACHALO_RAZBEGA = 0;

/** Адрес счётчика. Тот же домен, что и сайт: бот стоит за nginx. */
export const SCHETCHIK = '/api/schetchik';

/**
 * Годится ли пришедшее число.
 *
 * Проверяется отдельно и строго, потому что ответ приходит снаружи
 * сборки. Дробное, отрицательное, `null` при поломке базы, строка
 * вместо числа — всё это должно оставить засев, а не превратить
 * шапку в «Уже 2 417,5 пользователей» или в «Уже NaN».
 */
const godnoe = (n: unknown): n is number =>
  typeof n === 'number' && Number.isInteger(n) && n >= 0 && n < 1e9;

/**
 * Засев плюс выданные заказы.
 *
 * Возвращает число, которое можно рисовать сразу: до ответа —
 * засев, после — сумму. Отдельного «загружается» нет намеренно,
 * иначе в шапке на долю секунды висела бы заглушка.
 */
export function useSchetchik(zasev: number): number {
  const [vydano, setVydano] = useState(0);

  useEffect(() => {
    let zhiv = true;
    fetch(SCHETCHIK, { headers: { accept: 'application/json' } })
      .then((r) => (r.ok ? r.json() : Promise.reject(new Error(String(r.status)))))
      .then((d: { vydano?: unknown }) => {
        if (zhiv && godnoe(d.vydano)) setVydano(d.vydano);
      })
      .catch(() => {
        /* Не дозвонились — остаётся засев. Молча: сообщать человеку
           о нашей неудаче в подписи, которая ему ничего не обещала,
           значит тревожить его без всякого дела. */
      });
    return () => {
      zhiv = false;
    };
  }, []);

  return zasev + vydano;
}
