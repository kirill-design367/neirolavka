/**
 * Продавец: кто отвечает за лавку и как с ним связаться.
 *
 * Отдельный файл, а не строки в разметке подвала, по той же причине,
 * по какой каталог живёт в `catalog.ts`: эти данные появятся ещё
 * и на странице оферты, и второй экземпляр ИНН разъедется с первым
 * в день, когда его понадобится поправить. Разъедется молча —
 * реквизиты никто не перечитывает.
 *
 * ТЕЛЕФОН В ПОДВАЛЕ И ТЕЛЕФОН В РЕКВИЗИТАХ ОФЕРТЫ — РАЗНЫЕ, И ЭТО
 * РЕШЕНИЕ ВЛАДЕЛЬЦА, А НЕ РАСХОЖДЕНИЕ. Он сказал прямо: номер
 * в подвале отличается от номера в оферте, и сводить их к одному
 * нельзя. Соблазн «привести к единому» возникает ровно при чтении
 * такого файла — здесь стоит `telefon`, а в оферте будет свой,
 * и это два разных канала, а не одна опечатка.
 */

/** Как показать номер человеку и как отдать его набиралке. */
export type Telefon = {
  /** Для глаза: с пробелами и дефисами. */
  vidimyy: string;
  /** Для `tel:` — только плюс и цифры. */
  dlyaNabora: string;
};

/**
 * Номер для `tel:`.
 *
 * Считается ИЗ видимого, а не пишется рядом вторым полем: два
 * написания одного номера — это два источника правды, и они
 * разъезжаются при первой же правке. Пробелы, дефисы и скобки
 * в `tel:` формально допустимы, но часть набиралок на них спотыкается,
 * поэтому остаются только плюс и цифры.
 */
function dlyaNabora(vidimyy: string): string {
  const cifry = vidimyy.replace(/[^\d]/g, '');
  return vidimyy.trim().startsWith('+') ? `+${cifry}` : cifry;
}

export function telefon(vidimyy: string): Telefon {
  return { vidimyy, dlyaNabora: dlyaNabora(vidimyy) };
}

/** Правовой документ сайта. */
export type Dokument = {
  /** Адрес страницы: `/oferta`. */
  put: string;
  /** Как он называется в ссылке подвала. */
  nazvanie: string;
  /**
   * Есть ли страница на сайте НА САМОМ ДЕЛЕ.
   *
   * Тот же приём, что у `botReady` и `referralReady` в каталоге,
   * и заведён он здесь по причине более важной, чем там. Ссылка
   * из подвала коммерческого сайта на несуществующую оферту — это
   * не «пока пусто», а 404 на месте договора: человек, который
   * пошёл читать условия перед тем, как отдать деньги, упирается
   * в страницу «не найдено». Отсутствующая ссылка честнее битой.
   *
   * Ставится в `true` вместе с появлением самой страницы, не раньше.
   */
  gotov: boolean;
};

export type Prodavec = {
  imya: string;
  inn: string;
  ogrnip: string;
  telefon: Telefon;
  pochta: string;
  dokumenty: Dokument[];
};

const PRODAVEC: Prodavec = {
  imya: 'Менаше Лев Наумович',
  inn: '526324111452',
  ogrnip: '326527500140369',
  /* Не тот номер, что в реквизитах оферты, — см. шапку файла. */
  telefon: telefon('+7 950 373-80-46'),
  pochta: 'lev.menashe@yandex.ru',
  dokumenty: [
    /* Страница собрана из docx владельца (`docs/Оферта Лев.docx`),
       живёт по адресу /oferta — ссылка включена. */
    { put: '/oferta', nazvanie: 'Публичная оферта', gotov: true },
    /* ПОЛИТИКИ ОБРАБОТКИ ПЕРСОНАЛЬНЫХ ДАННЫХ ЗДЕСЬ НЕТ НАМЕРЕННО.
       Владелец решил её не делать, и ссылки на неё в подвале быть
       не должно. Строка не «забыта» и не ждёт включения флага —
       её нет вовсе, и дописывать её обратно «для полноты» нельзя:
       ссылка на несуществующий документ хуже её отсутствия. */
  ],
};

/**
 * Данные продавца.
 *
 * Компоненты обращаются сюда, а не к константе напрямую: когда
 * реквизиты поедут откуда-нибудь ещё, меняется тело этой функции,
 * а вызывающие места остаются нетронутыми. Тот же уговор, что
 * с `getCatalog()`.
 */
export function getProdavec(): Prodavec {
  return PRODAVEC;
}

/** Документы, которые действительно открываются. */
export function zhivyeDokumenty(): Dokument[] {
  return PRODAVEC.dokumenty.filter((d) => d.gotov);
}
