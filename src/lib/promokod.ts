/**
 * Промокод: правила кода, общие для сайта и бота.
 *
 * ОДИН ФАЙЛ НА ОБЕ СТОРОНЫ — то же решение, что с каталогом
 * (`catalog.ts`) и с меткой канала (`metka.ts`), и по той же причине.
 * Код набирает человек на сайте, а узнаёт его бот; между ними стоит
 * Telegram со своим ограничением на параметр `start`. Две копии
 * правил разъехались бы на первой правке: сайт начал бы слать то,
 * чего бот не находит, и человек видел бы в чеке скидку, которой
 * в заказе нет. Тише этой поломки не бывает — заметить её можно
 * только по жалобе покупателя.
 *
 * Отсюда всё устройство:
 *   • код приводится к `[A-Z0-9-]` — `_` занят под разделитель пар
 *     в payload, а строчные буквы отличались бы от прописных там,
 *     где человек их набирает от руки;
 *   • длина ограничена, потому что в `start` всего 64 знака, и рядом
 *     с промокодом едет метка канала;
 *   • сравнение идёт по НОРМАЛИЗОВАННОМУ виду с обеих сторон.
 *     «leto-25», «LETO 25» и «Leto—25» — это один и тот же код.
 */

/** Сколько знаков кода помещается, не съедая payload целиком. */
export const PREDEL_KODA = 16;

/** Ключ пары, под которым промокод едет в Telegram. */
export const KLYUCH_PROMO = 'promo';

/**
 * Привести к коду промокода.
 *
 * Прописные буквы не украшение: промокод человек читает с картинки
 * или из сообщения и набирает руками, а «l» и «I» в наборе строчных
 * и прописных вперемешку различаются плохо. Один регистр снимает
 * половину опечаток.
 *
 * Кириллица не выживает — ровно как в метке канала, и по той же
 * причине: Telegram её в `start` не пропустит. Поэтому «ЛЕТО» даёт
 * пустой код, то есть «кода нет», и это честнее молчаливой
 * подстановки чего-нибудь похожего.
 */
export function kodPromo(syroe: string | null | undefined): string {
  return (syroe ?? '')
    .toUpperCase()
    .replace(/[^A-Z0-9-]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, PREDEL_KODA)
    .replace(/-$/, '');
}

/**
 * Почему код не подошёл.
 *
 * Коды, а не фразы: фразу показывает сайт по-своему, а бот по-своему,
 * и одна строка на двоих однажды разъехалась бы с тем, что на самом
 * деле произошло.
 */
export type OtkazPromo =
  /** Такого кода нет вовсе — или он набран с ошибкой. */
  | 'net'
  /** Срок действия кончился. */
  | 'istyok'
  /** Активации кончились: код разобрали. */
  | 'konchilis'
  /** Владелец отключил код досрочно. */
  | 'otklyuchen'
  /** У выбранного нет объявленной цены — считать скидку не от чего. */
  | 'net_ceny';

/** Что сайт и бот отвечают на введённый код. */
export type ItogPromo =
  | { godit: true; kod: string; skidkaProc: number }
  | { godit: false; pochemu: OtkazPromo };

/**
 * Размер скидки в копейках.
 *
 * Считается ОТ ЦЕНЫ ТАРИФА, а не от того, что осталось заплатить
 * после баланса, — так просил владелец, и так это единственно
 * осмысленно: иначе человек с деньгами на балансе получал бы
 * скидку меньше объявленной, а человек с нулём — полную.
 *
 * Ноль цены — это «цена не объявлена» (см. `catalog.ts`), и скидка
 * от неё тоже ноль: процент от неизвестного — это неизвестное,
 * а не ноль рублей выгоды.
 */
export function skidkaKop(cenaKop: number, skidkaProc: number): number {
  if (cenaKop <= 0 || skidkaProc <= 0) return 0;
  return Math.min(cenaKop, Math.round((cenaKop * skidkaProc) / 100));
}

/** Сколько остаётся заплатить после скидки. Ниже нуля не бывает. */
export function kOplateKop(cenaKop: number, skidka: number): number {
  return Math.max(0, cenaKop - skidka);
}

/**
 * Объяснение отказа человеку — ОДНО на сайт и на бота.
 *
 * «Понятное объяснение почему» из задания: человек должен понять,
 * что делать дальше, а не получить слово «ошибка». Отключённый
 * досрочно код не называется истёкшим: это была бы неправда, а
 * враньё в мелочи стоит доверия ровно там, где его и проверяют.
 */
export function otkazSlovami(pochemu: OtkazPromo): string {
  switch (pochemu) {
    case 'net':
      return 'Такого промокода нет. Проверьте, не потерялась ли буква.';
    case 'istyok':
      return 'Срок действия промокода истёк.';
    case 'konchilis':
      return 'Активации промокода кончились — его уже разобрали.';
    case 'otklyuchen':
      return 'Промокод больше не действует.';
    case 'net_ceny':
      return 'Цена выбранного ещё не объявлена, поэтому скидку считать не от чего.';
  }
}
