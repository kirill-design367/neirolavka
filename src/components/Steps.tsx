'use client';

import { useMergedRefs, useParallax, useReveal, useStepTrack } from '@/lib/motion';

/** Покупка действительно идёт по шагам, поэтому нумерация здесь несёт смысл.
 *  Тексты утверждает владелец — стоят слово в слово так, как он их прислал. */
const STEPS = [
  {
    n: '1',
    title: 'Выбираете подписку',
    text: 'Claude, ChatGPT или другую нейросеть — выбираете прямо на сайте',
  },
  {
    n: '2',
    title: 'Оплачиваете безопасно',
    text: 'Картой российского банка или через СБП. Данные карты защищены шифрованием, мы их не храним.',
  },
  {
    n: '3',
    title: 'Получаете доступ',
    /* ЗДЕСЬ НАЗВАН ШАГ, КОТОРОГО РАНЬШЕ НЕ БЫЛО: после оплаты надо
       открыть бот по ссылке. До появления оплаты на сайте человек
       уходил в бот ДО денег, и говорить об этом было незачем; теперь
       между оплатой и выдачей стоит одно нажатие, и не сказать о нём
       значит потерять человека ровно там, где он уже заплатил.

       Строка стоит в шагах, а не в сноске чека: сноска от неё росла
       на две строки, и на 1366×768 чек упирался в собственную
       прокрутку. Шаги — то место, где читают порядок действий. */
    text: 'После оплаты откройте бот по ссылке — заказ уже там. Останется ответить, нужен новый аккаунт или подключить свой; логин и пароль приходят в Telegram.',
  },
];

export function Steps() {
  const ref = useMergedRefs(useReveal<HTMLElement>({ stagger: 0.08 }), useParallax<HTMLElement>());
  const trackRef = useStepTrack<HTMLOListElement>();

  return (
    <section className="steps" ref={ref}>
      <h2 className="steps__title" data-reveal>
        Как это работает
      </h2>

      {/* Не три одинаковые карточки, а одна нить: шаги нанизаны на линию,
          и видно, что это последовательность, а не список свойств. */}
      <ol className="steps__thread" data-parallax="0.8" ref={trackRef}>
        {/* Дорожка и бегущая по ней точка. Разметка одна на весь блок:
            подсвеченный участок должен быть непрерывным, а не собранным
            из отрезков между соседними шагами. */}
        <span className="steps__track" aria-hidden="true">
          <span className="steps__track-fill" />
          {/* Светодиод: ясная постоянная форма и яркое ядро. Ездит он
              не своей анимацией, а положением --led-pos — теми же
              часами, по которым вспыхивают цифры. */}
          <span className="steps__led">
            <span className="steps__led-core" />
          </span>
        </span>
        {STEPS.map((step) => (
          <li className="step" key={step.n}>
            <span className="step__node" aria-hidden="true">
              {/* Свечение — отдельный слой без текста: увеличивается
                  и гаснет оно. Сама цифра вспыхивает цветом, но
                  не масштабируется: масштаб на тексте растянул бы
                  готовый растр. */}
              <span className="step__halo" />
              <span className="step__num tnum">{step.n}</span>
            </span>
            <div className="step__body" data-reveal>
              <h3 className="step__title">{step.title}</h3>
              <p className="step__text">{step.text}</p>
            </div>
          </li>
        ))}
      </ol>

      {/* ПЛАШКА С ИНСТРУКЦИЕЙ СТОИТ СРАЗУ ПОД ТРЕМЯ ШАГАМИ, и место
          выбрано по трём доводам.

          Первый — она про ЭТИ ЖЕ три шага, только подробно
          и снимками. Значит её место там, где человек дочитал
          их и мог не понять: сразу под ними, а не в конце блока
          за примечанием о продлении, которое говорит о другом
          случае.

          Второй — внутрь <ol> её класть нельзя. Нумерация там
          сквозная, и плашка получила бы «4»; хуже того,
          `useStepTrack` считает дорожку по узлам шагов, и четвёртый
          узел растянул бы к ней светодиод. Ровно этот запрет
          записан про примечание, и он тот же самый.

          Третий — ритм. Три шага стоят в ряд по всей ширине; и её,
          и примечание в ту же ширину подряд читались бы двумя
          одинаковыми полками. Поэтому плашка ужата по содержимому
          (inline-flex), а примечание осталось широким: сначала
          короткая дверь, потом отдельная мысль.

          Материал — утопленная поверхность, а НЕ бумага чека:
          в тёмной теме `--c-paper` и `--c-deep` это один и тот же
          #1c3031, и плашка слилась бы с примечанием под ней
          в одно пятно. */}
      <a className="steps__pomoshch" href="/instrukciya/" data-reveal>
        <span className="steps__pomoshch-text">Помощь в оформлении заказа</span>
        <span className="steps__pomoshch-strelka" aria-hidden="true">
          →
        </span>
      </a>

      {/* ПРИМЕЧАНИЕ, А НЕ ЧЕТВЁРТЫЙ ШАГ, и различие держится тремя
          вещами сразу.

          Первая: оно вынесено ИЗ дорожки. Шаги — это <li> внутри
          <ol> с общей нитью и цифрой на ней; примечание лежит
          отдельным <aside> после списка, и нить до него не доходит.
          Цифры у него нет и быть не может — нумерация в <ol>
          сквозная, четвёртый пункт получил бы «4».

          Вторая: у него своя плоскость. Шаги стоят прямо на странице,
          примечание — на утопленной поверхности со скруглением.
          Перепад фона, а не линия-разделитель: линий в проекте нет.

          Третья: оно начинается ВОПРОСОМ. Шаг отвечает «что делать
          дальше», примечание — «а если у вас другой случай».

          Кегль при этом полный: внутри обещание про сохранность
          данных, а обещания в этом проекте не набирают сноской. */}
      <aside className="steps__note" data-reveal>
        <p className="steps__note-title">Продлеваете существующий аккаунт?</p>
        <p className="steps__note-text">
          Введите логин и пароль, подтвердите код с почты — и подписка продлится
          автоматически. Ваши данные в безопасности.
        </p>
      </aside>
    </section>
  );
}
